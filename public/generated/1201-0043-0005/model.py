plate = cq.Workplane('XY').box(43, 43, 7.5, centered=(True, True, False)).translate((0, 0, -7.5))
blocks = (cq.Workplane('XY').pushPoints([(16.5, 16.5), (-16.5, 16.5), (16.5, -16.5), (-16.5, -16.5)])
          .rect(10, 10).extrude(7.5))
body = plate.union(blocks)
bore = cq.Workplane('XY').workplane(offset=-10).circle(7).extrude(20)
notch = cq.Workplane('XY').workplane(offset=-10).center(0, 21.5).circle(7).extrude(20)
holes = (cq.Workplane('XY').workplane(offset=-10)
         .pushPoints([(8, 8), (-8, 8), (8, -8), (-8, -8)]).circle(1.75).extrude(20))
part = body.cut(bore).cut(notch).cut(holes).translate((0, 21.5, 0))