base = cq.Workplane('XY').box(26, 3, 40, centered=(True, False, True))
ear_l = cq.Workplane('XY').box(3, 30, 40, centered=(True, False, True)).translate((-11.5, 0, 0))
ear_r = cq.Workplane('XY').box(3, 30, 40, centered=(True, False, True)).translate((11.5, 0, 0))
part = base.union(ear_l).union(ear_r)
# 10 mm cross pin through both ears (axis X)
pin = cq.Workplane('YZ').center(22, 10).circle(5).extrude(15, both=True)
part = part.union(pin)
# two base mounting holes (axis Y)
holes = cq.Workplane('XZ').pushPoints([(0, -6), (0, -16)]).circle(3.25).extrude(10, both=True)
part = part.cut(holes)