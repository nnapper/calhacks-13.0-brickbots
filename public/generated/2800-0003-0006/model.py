shank = cq.Workplane('XY').circle(1.5).extrude(6)
head = cq.Workplane('XY').workplane(offset=6).circle(2.75).extrude(3)
screw = shank.union(head)
hex_cut = (cq.Workplane('XY').workplane(offset=7.5)
    .transformed(rotate=(0, 0, 90))
    .polygon(6, 2.5 / math.cos(math.radians(30))).extrude(1.5))
screw = screw.cut(hex_cut)
part = screw.rotate((0, 0, 0), (1, 0, 0), -90)