post = cq.Workplane('XY').pushPoints([(sx*16, 3.5, sz*11.75) for sx in (-1,1) for sz in (-1,1)]).eachpoint(lambda l: cq.Workplane('XY').box(6, 7, 8.5).val().moved(l))
plate = cq.Workplane('XZ', origin=(0, 8.5, 0)).circle(16).extrude(4)
body = plate.union(post)
bore = cq.Workplane('XZ', origin=(0, 8.5, 0)).circle(7).extrude(4)
cb = cq.Workplane('XZ', origin=(0, 8.5, 0)).circle(8).extrude(1)
holes1 = cq.Workplane('XZ', origin=(0, 8.5, 0)).pushPoints([(0, 12), (0, -12), (12, 0), (-12, 0)]).circle(1.65).extrude(4)
holes2 = cq.Workplane('XZ', origin=(0, 8.5, 0)).pushPoints([(8.5, 8.5), (-8.5, 8.5), (8.5, -8.5), (-8.5, -8.5)]).circle(2.25).extrude(4)
posthole = cq.Workplane('XY', origin=(0, 0, 0)).pushPoints([(-16, 3), (16, 3)]).circle(1.65).extrude(20, both=True)
part = body.cut(bore).cut(cb).cut(holes1).cut(holes2).cut(posthole)